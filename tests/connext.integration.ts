import "dotenv/config";
import {describe,it,expect,vi,beforeAll,afterAll} from "vitest";
import {randomUUID} from "node:crypto";
vi.mock("@upstash/redis",()=>({Redis:class{get(){return Promise.resolve(true)}}}));
vi.mock("../src/lib/redis",()=>({redisConnection:()=>({url:"https://unused.example",token:"test"})}));
import {db} from "../src/lib/db";
import {createConnext,acceptConnext,drainConnext} from "../src/modules/connext";
const suite=process.env.RUN_DB_TESTS==="1"?describe:describe.skip;
suite("Connext real PostgreSQL, simulated notification only",()=>{
 let userId:string;const suffix=randomUUID();
 beforeAll(async()=>{
  if(!process.env.DATABASE_URL?.includes("canteen_test"))throw Error("Dedicated test database required");
  for(const [key,value] of Object.entries({PAYMENT_MODE:"slip2go",SLIP2GO_SECRET_KEY:"test",TOPUP_BANK_CODE:"006",TOPUP_BANK_ACCOUNT:"1234568619",TOPUP_ACCOUNT_NAME:"Test",TOPUP_PROMPTPAY:"0812345678"}))vi.stubEnv(key,value);
  userId=(await db.user.create({data:{status:"ACTIVE",email:`connext-${suffix}@example.test`,wallet:{create:{}}}})).id;
  await db.auditLog.create({data:{action:"TOPUP_MODE_CHANGED",actorId:"test",targetId:"test",detail:"connext"}});
 });
 afterAll(async()=>{vi.unstubAllEnvs();await db.$disconnect();});
 it("reserves distinct amounts and credits exactly once under concurrent delivery",async()=>{
  const [a,b]=await Promise.all([createConnext(userId,10000,randomUUID()),createConnext(userId,10000,randomUUID())]);
  expect(a.amount).not.toBe(b.amount);
  const now=new Date();const parts=new Intl.DateTimeFormat("en-GB",{timeZone:"Asia/Bangkok",day:"2-digit",month:"2-digit",year:"numeric",hour:"2-digit",minute:"2-digit",hour12:false}).formatToParts(now);const get=(type:string)=>parts.find(x=>x.type===type)!.value;
  const text=`เงินเข้า: ${(a.amount/100).toFixed(2)} บาท เข้าบัญชี XX8619 เมื่อ ${get("day")}/${get("month")}/${String(Number(get("year"))+543).slice(-2)} ${get("hour")}:${get("minute")} ยอดเงินที่ใช้ได้ 999,999.00 บาท`;
  const results=await Promise.all([acceptConnext(text),acceptConnext(text)]);
  expect(results.every(x=>x.queued)).toBe(true);
  expect((await db.wallet.findUniqueOrThrow({where:{userId}})).balance).toBe(0);
  await Promise.all([drainConnext(100),drainConnext(100),drainConnext(100)]);
  expect((await db.wallet.findUniqueOrThrow({where:{userId}})).balance).toBe(a.amount);
  expect(await db.ledgerTransaction.count({where:{reference:a.id}})).toBe(1);
  await acceptConnext(text);await drainConnext(100);
  expect((await db.wallet.findUniqueOrThrow({where:{userId}})).balance).toBe(a.amount);
  await expect(acceptConnext(text.replace("XX8619","XX0000"))).rejects.toThrow("CONNEXT_ACCOUNT");
 });
 it("recovers an expired worker lease and retries an unmatched durable event",async()=>{
  const id=randomUUID();const member=await db.user.create({data:{email:`retry-${id}@example.test`,status:"ACTIVE",wallet:{create:{}}},include:{wallet:true}});
  const amount=700000+Math.floor(Math.random()*200000);const now=new Date();
  const parts=new Intl.DateTimeFormat("en-GB",{timeZone:"Asia/Bangkok",day:"2-digit",month:"2-digit",year:"numeric",hour:"2-digit",minute:"2-digit",hour12:false}).formatToParts(now);const get=(t:string)=>parts.find(x=>x.type===t)!.value;
  const text=`เงินเข้า: ${(amount/100).toFixed(2)} บาท เข้าบัญชี XX8619 เมื่อ ${get("day")}/${get("month")}/${String(Number(get("year"))+543).slice(-2)} ${get("hour")}:${get("minute")} ยอดเงินที่ใช้ได้ 777,777.77 บาท`;
  const job=await acceptConnext(text);
  await db.connextWorker.upsert({where:{id:"settlement"},create:{id:"settlement",lease:id,lockedUntil:new Date(Date.now()+60000)},update:{lease:id,lockedUntil:new Date(Date.now()+60000)}});
  expect((await drainConnext()).processed).toBe(0);
  await db.connextWorker.update({where:{id:"settlement"},data:{lockedUntil:new Date(0)}});
  await drainConnext(100);
  const failed=await db.connextJob.findUniqueOrThrow({where:{id:job.id}});expect(failed.status).toBe("PENDING");expect(failed.attempts).toBe(1);
  const intent=await db.topupIntent.create({data:{walletId:member.wallet!.id,key:id,provider:"connext",amount,expiresAt:new Date(Date.now()+900000)}});
  await db.connextJob.update({where:{id:job.id},data:{availableAt:new Date(0)}});
  await drainConnext(100);
  expect((await db.connextJob.findUniqueOrThrow({where:{id:job.id}})).status).toBe("DONE");
  expect((await db.wallet.findUniqueOrThrow({where:{id:member.wallet!.id}})).balance).toBe(amount);
  expect(await db.ledgerTransaction.count({where:{reference:intent.id}})).toBe(1);
 });
 it("allocates beyond 99 concurrent amounts and reuses expired reservations",async()=>{
  const ids=Array.from({length:110},()=>randomUUID());const base=40000+Math.floor(Math.random()*1000)*100;
  await db.user.createMany({data:ids.map(id=>({id,email:`slots-${id}@example.test`,status:"ACTIVE"}))});
  await db.wallet.createMany({data:ids.map(userId=>({userId}))});
  const results=await Promise.all(ids.map(id=>createConnext(id,base,randomUUID())));
  expect(new Set(results.map(x=>x.amount)).size).toBe(110);expect(results.map(x=>x.amount)).toContain(base-101);
  expect(Math.max(...results.map(x=>x.amount))).toBe(base-1);
  const first=results.find(x=>x.amount===base-1)!;
  await db.topupIntent.update({where:{id:first.id},data:{expiresAt:new Date(Date.now()-300000)}});
  await db.connextReservation.update({where:{amount:first.amount},data:{holdUntil:new Date(0)}});
  const reused=await createConnext(ids[0],base,randomUUID());expect(reused.amount).toBe(base-1);
 },30000);
});
