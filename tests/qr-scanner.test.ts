import { expect, it } from "vitest";
import QRCode from "qrcode";
import jsQR from "jsqr";
import { memberQrToken } from "@/lib/member-qr";
it("decodes the same opaque-token QR format generated by the member wallet", () => {
  const token = "aB0_-".repeat(8) + "xyz";
  const qr = QRCode.create(token, { errorCorrectionLevel: "M" });
  const scale = 6, quiet = 4, width = (qr.modules.size + 2 * quiet) * scale;
  const pixels = new Uint8ClampedArray(width * width * 4);
  for (let y = 0; y < width; y++) for (let x = 0; x < width; x++) {
    const mx = Math.floor(x / scale) - quiet, my = Math.floor(y / scale) - quiet;
    const dark = mx >= 0 && my >= 0 && mx < qr.modules.size && my < qr.modules.size && qr.modules.get(my, mx);
    const offset = (y * width + x) * 4;
    pixels[offset] = pixels[offset+1] = pixels[offset+2] = dark ? 0 : 255;
    pixels[offset+3] = 255;
  }
  const result = jsQR(pixels, width, width, { inversionAttempts: "dontInvert" });
  expect(result?.data).toBe(token);
  expect(memberQrToken(result!.data)).toBe(token);
});
it("rejects links, bank QR payloads and malformed data without navigating or charging", () => {
  for (const value of ["https://evil.example/qr", "0002010102122937", "<script>alert(1)</script>", "", "x".repeat(10000)])
    expect(memberQrToken(value)).toBeNull();
});
